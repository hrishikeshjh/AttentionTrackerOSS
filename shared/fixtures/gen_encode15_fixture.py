"""
Generates shared/fixtures/encode15_v2.json: the v2.0 FEATURE_VECTOR_VERSION 2
(15-dim) encoding of the cases in encode13_cross_language.json (generated from
the v1.0 TypeScript), plus posture cases.

Run from the repo root:  python3 shared/fixtures/gen_encode15_fixture.py
Checked by v2.0/tests/test_feature_vector_v2_contract.py (regenerates in memory
and compares) and by v1.0's temporal-classifier loadModel(featureDim: 15)
contract test (the browser pads with posture_unknown).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "v2.0"))

from features.feature_vector import (  # noqa: E402
    FEATURE_DIM,
    FEATURE_DIM_V1,
    FEATURE_NAMES_V2,
    FEATURE_VECTOR_VERSION,
    POSTURE_UNKNOWN,
    encode_feature_vector_v2,
)

POSTURES = [
    {"name": "unknown", "is_upright": None, "lean_angle": None},
    {"name": "upright_5deg", "is_upright": True, "lean_angle": 5.0},
    {"name": "leaning_30deg", "is_upright": False, "lean_angle": 30.0},
    {"name": "lean_only_10deg", "is_upright": None, "lean_angle": 10.0},
    {"name": "clamped_120deg", "is_upright": False, "lean_angle": 120.0},
]


def build() -> dict:
    src = json.loads((HERE / "encode13_cross_language.json").read_text())
    cases = []
    for c in src["cases"]:
        m = c["metrics"]
        for p in POSTURES:
            v = encode_feature_vector_v2(
                gaze_x=m["gazeX"], gaze_y=m["gazeY"], pitch=m["pitch"], yaw=m["yaw"], ear=m["ear"],
                perclos=m["perclos"], stability=m["headPoseStability"], fidget=m["fidgetScore"],
                detected_objects=c["objects"], hand_proximity=c["handProximity"],
                is_upright=p["is_upright"], lean_angle=p["lean_angle"],
            )
            cases.append({"case": c["name"], "posture": p, "v2_encode15": [round(float(x), 7) for x in v]})
    return {
        "_comment": "GENERATED by shared/fixtures/gen_encode15_fixture.py from v2.0/features/feature_vector.py. Do not edit.",
        "feature_vector_version": FEATURE_VECTOR_VERSION,
        "feature_dim": FEATURE_DIM,
        "feature_dim_v1": FEATURE_DIM_V1,
        "feature_names": list(FEATURE_NAMES_V2),
        "posture_unknown": list(POSTURE_UNKNOWN),
        "sign_convention": "pitch_norm (index 2) and gaze_y (index 1): head/eyes DOWN = NEGATIVE",
        "v1_load_model_feature_dim_15_padding": list(POSTURE_UNKNOWN),
        "cases": cases,
    }


if __name__ == "__main__":
    out = HERE / "encode15_v2.json"
    out.write_text(json.dumps(build(), indent=2) + "\n")
    print(f"wrote {out}")
