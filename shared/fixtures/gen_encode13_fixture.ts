/**
 * Generates shared/fixtures/encode13_cross_language.json from the SHIPPED v1.0
 * TypeScript encoder, so the v2.0 Python test
 * (v2.0/tests/test_cross_language_contract.py) compares against real TS output
 * rather than hand-typed numbers.
 *
 * Run from v1.0/ (uses v1.0's tsx; reads v1.0 sources, writes only the JSON):
 *   cd v1.0 && npx tsx ../shared/fixtures/gen_encode13_fixture.ts
 *
 * Sources read:
 *   v1.0/src/lib/scoring/dace/feature-vector.ts  encode13, PROXIMITY_CODES_V1
 *   v1.0/src/lib/temporal-classifier.ts          PROXIMITY_CODES_V2, MODEL_CLASSES,
 *                                                packWindow, softmax (loadModel contract)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { encode13, FEATURE_NAMES_13, PROXIMITY_CODES_V1 } from '../../v1.0/src/lib/scoring/dace/feature-vector';
import {
  MODEL_CLASSES,
  packWindow,
  PROXIMITY_CODES_V2,
  softmax,
} from '../../v1.0/src/lib/temporal-classifier';

type Prox = 'hands_not_visible' | 'hands_on_desk' | 'holding_pen' | 'holding_book' | 'holding_phone';

type Case = {
  name: string;
  metrics: {
    gazeX: number | null;
    gazeY: number | null;
    pitch: number | null;
    yaw: number | null;
    ear: number | null;
    perclos: number;
    headPoseStability: number;
    fidgetScore: number;
  };
  objects: string[];
  handProximity: Prox;
};

const base = {
  gazeX: 0.1, gazeY: -0.2, pitch: 12.6, yaw: -4, ear: 0.3,
  perclos: 5, headPoseStability: 90, fidgetScore: 5,
};

const PROX: Prox[] = ['hands_not_visible', 'hands_on_desk', 'holding_pen', 'holding_book', 'holding_phone'];

const cases: Case[] = [
  { name: 'neutral_screen', metrics: { ...base }, objects: [], handProximity: 'hands_not_visible' },
  ...PROX.map((p) => ({ name: `proximity_${p}`, metrics: { ...base }, objects: ['book'], handProximity: p })),
  { name: 'phone_and_laptop', metrics: { ...base, pitch: -20 }, objects: ['phone', 'laptop'], handProximity: 'holding_phone' },
  { name: 'notebook_counts_as_book', metrics: { ...base }, objects: ['notebook'], handProximity: 'holding_book' },
  { name: 'unknown_object_is_none', metrics: { ...base }, objects: ['cup'], handProximity: 'hands_on_desk' },
  { name: 'nulls_use_defaults', metrics: { ...base, gazeX: null, gazeY: null, pitch: null, yaw: null, ear: null }, objects: [], handProximity: 'hands_not_visible' },
  { name: 'ear_exactly_zero', metrics: { ...base, ear: 0 }, objects: [], handProximity: 'hands_not_visible' },
  { name: 'clamping', metrics: { gazeX: 1.7, gazeY: -3, pitch: 135, yaw: -200, ear: 1.4, perclos: 150, headPoseStability: -10, fidgetScore: 250 }, objects: [], handProximity: 'hands_not_visible' },
  { name: 'negative_pitch_down_convention', metrics: { ...base, pitch: -33.3, gazeY: -0.6 }, objects: ['book'], handProximity: 'holding_book' },
];

const caseOut = cases.map((c) => {
  const v1 = encode13({
    metrics: c.metrics,
    detectedObjects: c.objects.map((cls) => ({ class: cls, confidence: 0.9, bbox: { x: 0.5, y: 0.5, width: 0.1, height: 0.1 } })) as never,
    handProximity: c.handProximity,
  });
  // What TemporalBehaviorClassifier.onnxClassify() feeds a loaded model with
  // the default proximityCodes='v2': the same vector with index 12 re-encoded.
  const model = [...v1];
  model[12] = PROXIMITY_CODES_V2[c.handProximity] ?? 0;
  return { ...c, v1_encode13: v1, v1_model_input: model };
});

// One 15-frame window: frame t has every feature f set to f + t / 100 so the
// packing order is unambiguous.
const T = 15;
const F = 13;
const window = Array.from({ length: T }, (_, t) => Array.from({ length: F }, (_, f) => f + t / 100));
const logits = [2.0, 1.0, 0.5, -1.0, 0.0, -3.0];

const out = {
  _comment:
    'GENERATED by shared/fixtures/gen_encode13_fixture.ts from the shipped v1.0 TypeScript. Do not edit by hand. ' +
    'Consumed by v2.0/tests/test_cross_language_contract.py.',
  feature_names: FEATURE_NAMES_13,
  proximity_codes_v1_rules: PROXIMITY_CODES_V1,
  proximity_codes_v2_model: PROXIMITY_CODES_V2,
  model_classes: MODEL_CLASSES,
  // Hand-copied from the loadModel() header/defaults in temporal-classifier.ts
  // (the resolved defaults are private to loadModel, so they cannot be imported).
  load_model_defaults_documented: { inputName: 'input', outputName: 'logits', layout: 'channels_first', outputIsLogits: true, proximityCodes: 'v2' },
  cases: caseOut,
  window: {
    frames: window,
    dims_channels_first: [1, F, T],
    packed_channels_first: Array.from(packWindow(window, 'channels_first')),
  },
  softmax: { logits, probs: softmax(logits) },
};

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, 'encode13_cross_language.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${cases.length} cases`);
