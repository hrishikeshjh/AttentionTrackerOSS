"""
FEATURE_VECTOR_VERSION 2 contract (15 dims = v1.0-compatible 13 + posture).

shared/fixtures/encode15_v2.json is generated by
shared/fixtures/gen_encode15_fixture.py from the Python encoder over the cases of
the TypeScript-generated encode13 fixture. This test (light tier):
  - regenerates it in memory (stale fixture -> fail),
  - checks the first 13 channels equal v1.0's model input for every case
    (so the 13-dim v1.0 contract is untouched),
  - pins posture encoding and the unknown-posture padding v1.0
    loadModel(featureDim: 15) appends,
  - checks the synthetic generator, the dataset base and the trained v3 model
    use the same version / dimension and sign convention.

Run: pytest v2.0/tests/test_feature_vector_v2_contract.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pytest

V2_ROOT = Path(__file__).parent.parent
REPO_ROOT = V2_ROOT.parent
sys.path.insert(0, str(V2_ROOT))
sys.path.insert(0, str(REPO_ROOT / "shared" / "fixtures"))

from features.feature_vector import (  # noqa: E402
    FEATURE_DIM,
    FEATURE_DIM_V1,
    FEATURE_NAMES_V2,
    FEATURE_VECTOR_VERSION,
    POSTURE_UNKNOWN,
    encode_posture,
)

FX15 = REPO_ROOT / "shared" / "fixtures" / "encode15_v2.json"
FX13 = REPO_ROOT / "shared" / "fixtures" / "encode13_cross_language.json"


@pytest.fixture(scope="module")
def fx15():
    if not FX15.exists() or not FX13.exists():
        pytest.skip("shared fixtures missing")
    return json.loads(FX15.read_text())


def test_versions_and_names(fx15):
    assert FEATURE_VECTOR_VERSION == fx15["feature_vector_version"] == 2
    assert FEATURE_DIM == fx15["feature_dim"] == 15
    assert FEATURE_DIM_V1 == fx15["feature_dim_v1"] == 13
    assert list(FEATURE_NAMES_V2) == fx15["feature_names"]
    assert tuple(fx15["posture_unknown"]) == POSTURE_UNKNOWN == (1.0, 0.0)


def test_fixture_is_up_to_date(fx15):
    import gen_encode15_fixture as gen
    assert json.loads(json.dumps(gen.build())) == fx15


def test_first_13_equal_v1_model_input(fx15):
    v1 = {c["name"]: c["v1_model_input"] for c in json.loads(FX13.read_text())["cases"]}
    assert {c["case"] for c in fx15["cases"]} == set(v1)
    for c in fx15["cases"]:
        np.testing.assert_allclose(c["v2_encode15"][:13], v1[c["case"]], atol=1e-6, err_msg=c["case"])
        if c["posture"]["name"] == "unknown":
            # exactly what v1.0 loadModel(featureDim: 15) feeds: v1 input + padding
            assert c["v2_encode15"][13:] == fx15["v1_load_model_feature_dim_15_padding"]


def test_posture_encoding():
    class _P:
        is_upright, lean_angle = False, 45.0
    assert encode_posture(None) == POSTURE_UNKNOWN
    assert encode_posture(_P()) == (0.0, 0.5)
    assert encode_posture(is_upright=None, lean_angle=10.0) == (1.0, pytest.approx(10 / 90))
    assert encode_posture(is_upright=True, lean_angle=200.0) == (1.0, 1.0)


def test_dataset_and_synthetic_generator_use_v2():
    from training.datasets import base_dataset as bd
    from training.datasets.realistic_synthetic_loader import RealisticSyntheticDataset
    assert bd.FEATURE_DIM == FEATURE_DIM and bd.BaseBehaviorDataset.encode_feature().shape == (FEATURE_DIM,)
    ds = RealisticSyntheticDataset(split="val", n_per_class=60, augment_factor=0, seed=7)
    assert ds._windows.shape[1:] == (15, FEATURE_DIM)
    up, lean = ds._windows[..., 13], ds._windows[..., 14]
    assert set(np.unique(up)) <= {0.0, 1.0} and lean.min() >= 0 and lean.max() <= 1


def test_synthetic_signs_match_the_convention():
    """Reading / phone windows look DOWN = negative pitch_norm and gaze_y;
    screen windows sit at the reference (~0)."""
    from training.datasets.base_dataset import CLASS_TO_IDX
    from training.datasets.realistic_synthetic_loader import RealisticSyntheticDataset
    ds = RealisticSyntheticDataset(split="val", n_per_class=200, augment_factor=0, seed=11)
    for cls in ("attentive_reading", "using_phone"):
        w = ds._windows[ds._labels == CLASS_TO_IDX[cls]]
        assert w[..., 2].mean() <= -15 / 90, cls      # relative pitch at least 15 deg down
        assert w[..., 1].mean() <= -0.4, cls          # eyes down
    w = ds._windows[ds._labels == CLASS_TO_IDX["attentive_screen"]]
    assert abs(w[..., 2].mean()) < 0.05 and abs(w[..., 1].mean()) < 0.1


def test_v3_model_has_15_channels():
    ort = pytest.importorskip("onnxruntime")
    path = V2_ROOT / "models" / "behavior_classifier_v3.onnx"
    if not path.exists():
        pytest.skip("v3 model not present")
    sess = ort.InferenceSession(str(path))
    assert list(sess.get_inputs()[0].shape[1:]) == [FEATURE_DIM, 15]
    from server.config import BEHAVIOR_CLASSIFIER_MODEL
    assert BEHAVIOR_CLASSIFIER_MODEL.name == "behavior_classifier_v3.onnx"
